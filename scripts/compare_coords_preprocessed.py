def amino_acid_id_to_name(aatype_id):
    """将氨基酸类型ID转换为三字母名称"""
    amino_acid_names = [
        'ALA', 'ARG', 'ASN', 'ASP', 'CYS',
        'GLN', 'GLU', 'GLY', 'HIS', 'ILE',
        'LEU', 'LYS', 'MET', 'PHE', 'PRO',
        'SER', 'THR', 'TRP', 'TYR', 'VAL'
    ]
    return amino_acid_names[aatype_id]


def coordinates_to_pdb(coordinates, aatype, output_path, 
                      protein_name="PROTEIN", chain_id="A", ca_only=True):
    """
    将重建的坐标序列转换为PDB文件（与 inferencer_far.py 中的实现一致）
    Args:
        coordinates: [num_residues, 3, num_frames] 重建的CA原子坐标序列
        aatype: [num_residues] 氨基酸类型ID (0-19)
        output_path: 输出PDB文件路径
        protein_name: 蛋白质名称
        chain_id: 链ID
        ca_only: 是否只写CA原子
    """
    num_residues, _, num_frames = coordinates.shape
    
    with open(output_path, 'w') as f:
        f.write("REMARK  Generated by ProteinSpectrumFAR Reconstruction\n")
        f.write(f"REMARK  Protein: {protein_name}\n")
        f.write(f"REMARK  Number of residues: {num_residues}\n")
        f.write(f"REMARK  Number of frames: {num_frames}\n")
        f.write(f"TITLE     {protein_name} FAR Reconstruction\n")
        
        for frame_idx in range(num_frames):
            f.write(f"MODEL     {frame_idx + 1:4d}\n")
            
            atom_idx = 1
            for res_idx in range(num_residues):
                ca_coord = coordinates[res_idx, :, frame_idx].cpu().numpy() if isinstance(coordinates, torch.Tensor) else coordinates[res_idx, :, frame_idx]
                aa_name = amino_acid_id_to_name(aatype[res_idx].item() if isinstance(aatype, torch.Tensor) else aatype[res_idx])
                
                if ca_only:
                    # 只写CA原子
                    f.write(
                        f"ATOM  {atom_idx:5d}  CA  {aa_name} {chain_id}{res_idx + 1:4d}    "
                        f"{ca_coord[0]:8.3f}{ca_coord[1]:8.3f}{ca_coord[2]:8.3f}  "
                        f"1.00  0.00           C\n"
                    )
                    atom_idx += 1
                else:
                    # 写完整骨架原子(估计位置)
                    # CA原子
                    f.write(
                        f"ATOM  {atom_idx:5d}  CA  {aa_name} {chain_id}{res_idx + 1:4d}    "
                        f"{ca_coord[0]:8.3f}{ca_coord[1]:8.3f}{ca_coord[2]:8.3f}  "
                        f"1.00  0.00           C\n"
                    )
                    atom_idx += 1
                    
                    # C原子(估计位置)
                    c_coord = ca_coord + np.array([1.53, 0.0, 0.0])
                    f.write(
                        f"ATOM  {atom_idx:5d}  C   {aa_name} {chain_id}{res_idx + 1:4d}    "
                        f"{c_coord[0]:8.3f}{c_coord[1]:8.3f}{c_coord[2]:8.3f}  "
                        f"1.00  0.00           C\n"
                    )
                    atom_idx += 1
                    
                    # N原子(估计位置)
                    n_coord = ca_coord + np.array([-1.33, 0.0, 0.0])
                    f.write(
                        f"ATOM  {atom_idx:5d}  N   {aa_name} {chain_id}{res_idx + 1:4d}    "
                        f"{n_coord[0]:8.3f}{n_coord[1]:8.3f}{n_coord[2]:8.3f}  "
                        f"1.00  0.00           N\n"
                    )
                    atom_idx += 1
                    
                    # O原子(估计位置)
                    o_coord = c_coord + np.array([0.0, 1.24, 0.0])
                    f.write(
                        f"ATOM  {atom_idx:5d}  O   {aa_name} {chain_id}{res_idx + 1:4d}    "
                        f"{o_coord[0]:8.3f}{o_coord[1]:8.3f}{o_coord[2]:8.3f}  "
                        f"1.00  0.00           O\n"
                    )
                    atom_idx += 1
            
            f.write("TER\n")
            f.write("ENDMDL\n")
        
        f.write("END\n")
    
    logging.info(f"PDB文件已保存至: {output_path}")
    logging.info(f"模式: {'仅CA原子' if ca_only else '完整骨架原子'}")
    if isinstance(coordinates, torch.Tensor):
        logging.info(
            f"坐标范围: X[{coordinates[:, 0, :].min():.3f}, {coordinates[:, 0, :].max():.3f}], "
            f"Y[{coordinates[:, 1, :].min():.3f}, {coordinates[:, 1, :].max():.3f}], "
            f"Z[{coordinates[:, 2, :].min():.3f}, {coordinates[:, 2, :].max():.3f}]"
        )


def compare_coords_preprocessed(
    data_path: str,
    protein_idx: int = 0,
    window_idx: int = 0,
    device: str = "cuda",
    fft_norm: str = "ortho",
    scaling_factor_path: str = None,
):
    """
    比较两种方式得到的预处理坐标：
    1. 从频谱重建但不做invert_preprocessing
    2. 直接使用coords_preprocessed_windows
    """
    logging.info(f"加载数据: {data_path}")
    data_list = torch.load(data_path, weights_only=False)
    
    if protein_idx >= len(data_list):
        raise ValueError(f"protein_idx {protein_idx} >= {len(data_list)}")
    
    protein_data = data_list[protein_idx]
    protein_id = protein_data.get("id", f"protein_{protein_idx}")
    positions = protein_data["positions"]
    
    logging.info(f"处理蛋白质: {protein_id}")
    
    # 检查是否有fft_window数据
    x_fft_windows = positions.get("x_fft_windows", [])
    if not x_fft_windows:
        raise ValueError(f"{protein_id}: 未找到 x_fft_windows")
    
    if window_idx >= len(x_fft_windows):
        raise ValueError(f"window_idx {window_idx} >= {len(x_fft_windows)}")
    
    window_size = int(positions.get("fft_window_size"))
    coords_preprocessed_windows = positions.get("coords_preprocessed_fft_windows", [])
    
    if not coords_preprocessed_windows:
        raise ValueError(f"{protein_id}: 未找到 coords_preprocessed_fft_windows")
    
    logging.info(f"窗口大小: {window_size}, 窗口数量: {len(x_fft_windows)}")
    logging.info(f"当前窗口索引: {window_idx}")
    
    # 方法1: 直接使用coords_preprocessed_windows
    coords_preprocessed_direct = coords_preprocessed_windows[window_idx]  # (window_size, N, 3)
    logging.info(f"方法1 (直接): shape={coords_preprocessed_direct.shape}")
    
    # 方法2: 从频谱重建但不做invert_preprocessing
    device_obj = torch.device(device)
    
    # 加载scaling factors（如果数据是归一化的）
    scaling_factors = None
    if scaling_factor_path and os.path.exists(scaling_factor_path):
        scaling_factors = torch.tensor(torch.load(scaling_factor_path, weights_only=False), dtype=torch.float32)
        logging.info(f"加载scaling factors: shape={tuple(scaling_factors.shape)}")
    else:
        # 尝试自动查找
        data_dir = os.path.dirname(data_path)
        candidates = [
            os.path.join(data_dir, "fft_window2500_scaling_factors.pth"),
            os.path.join(data_dir, "fft_window5000_scaling_factors.pth"),
            os.path.join(data_dir, "atlas_10_scaling_factors.pth"),
        ]
        for candidate in candidates:
            if os.path.exists(candidate):
                scaling_factors = torch.tensor(torch.load(candidate, weights_only=False), dtype=torch.float32)
                logging.info(f"自动找到scaling factors: {candidate}, shape={tuple(scaling_factors.shape)}")
                break
    
    # 构建频谱
    x_windows = positions["x_fft_windows"][window_idx]
    y_windows = positions["y_fft_windows"][window_idx]
    z_windows = positions["z_fft_windows"][window_idx]
    
    spectrum_x_real = [item[:, 0] for item in x_windows]
    spectrum_x_imag = [item[:, 1] for item in x_windows]
    spectrum_y_real = [item[:, 0] for item in y_windows]
    spectrum_y_imag = [item[:, 1] for item in y_windows]
    spectrum_z_real = [item[:, 0] for item in z_windows]
    spectrum_z_imag = [item[:, 1] for item in z_windows]
    
    spectrum = np.stack(
        [
            spectrum_x_real,
            spectrum_x_imag,
            spectrum_y_real,
            spectrum_y_imag,
            spectrum_z_real,
            spectrum_z_imag,
        ],
        axis=-1,
    )  # [N, F, 6]
    spectrum_tensor = torch.tensor(spectrum, dtype=torch.float32).unsqueeze(-1).to(device_obj)  # [N, F, 6, 1]
    
    # 反归一化频谱（如果数据是归一化的）
    if scaling_factors is not None:
        spectrum_squeezed = spectrum_tensor.squeeze(-1)  # [N, F, 6]
        freq_len = spectrum_squeezed.shape[1]
        scale = scaling_factors.to(device=device_obj, dtype=torch.float32)
        if scale.numel() >= freq_len:
            scale = scale[:freq_len]
        else:
            pad = scale[-1].repeat(freq_len - scale.numel())
            scale = torch.cat([scale, pad], dim=0)
        scale = scale.view(1, -1, 1)  # (1, F, 1) for broadcasting
        
        # 反归一化：real和imag都乘以scale
        spectrum_squeezed = spectrum_squeezed * scale
        logging.info(f"已反归一化频谱，使用scaling factors")
    else:
        spectrum_squeezed = spectrum_tensor.squeeze(-1)  # [N, F, 6]
        logging.info(f"未找到scaling factors，跳过反归一化")
    
    # 获取frame0
    frame0 = torch.tensor(
        np.stack(
            [
                positions["x0_fft_windows"][window_idx],
                positions["y0_fft_windows"][window_idx],
                positions["z0_fft_windows"][window_idx],
            ],
            axis=-1,
        ),
        dtype=torch.float32,
    ).to(device_obj)  # (N, 3)
    
    # 重建坐标（不做invert_preprocessing）
    # 注意：频谱是从displacement的FFT得到的，displacement = x_proc - frame0
    # 所以重建时：x_proc = displacement + frame0
    # 使用与 inferencer_far.py 中 _reconstruct_window_coords 相同的逻辑
    spec_x = torch.complex(spectrum_squeezed[..., 0], spectrum_squeezed[..., 1])
    spec_y = torch.complex(spectrum_squeezed[..., 2], spectrum_squeezed[..., 3])
    spec_z = torch.complex(spectrum_squeezed[..., 4], spectrum_squeezed[..., 5])
    
    # 使用 irfft（与 inferencer_far.py 中的 irfft_full 一致）
    # irfft 期望输入是只包含正频率的复数频谱，输出是实数信号
    # irfft_full 的实现: torch.fft.irfft(spectrum, n=window_size, dim=-1, norm=norm)
    disp_x = torch.fft.irfft(spec_x, n=window_size, dim=-1, norm=fft_norm)
    disp_y = torch.fft.irfft(spec_y, n=window_size, dim=-1, norm=fft_norm)
    disp_z = torch.fft.irfft(spec_z, n=window_size, dim=-1, norm=fft_norm)
    
    # displacement是相对于frame0的，所以x_proc = displacement + frame0
    # 注意：irfft 已经指定了 n=window_size，所以输出长度已经是 window_size，无需再截断
    displacement = torch.stack([disp_x, disp_y, disp_z], dim=1)  # (N, 3, window_size)
    x_proc = displacement + frame0.unsqueeze(-1)  # (N, 3, window_size)
    
    # 转换为 (window_size, N, 3) 格式以便比较（与coords_preprocessed_direct格式一致）
    coords_reconstructed_permuted = x_proc.permute(2, 0, 1).contiguous().cpu().numpy()  # (window_size, N, 3)
    logging.info(f"方法2 (重建): shape={coords_reconstructed_permuted.shape}")
    
    # 比较
    diff = coords_preprocessed_direct - coords_reconstructed_permuted
    abs_diff = np.abs(diff)
    max_diff = np.max(abs_diff)
    mean_diff = np.mean(abs_diff)
    std_diff = np.std(abs_diff)
    
    # 计算相对误差
    coords_norm = np.linalg.norm(coords_preprocessed_direct, axis=-1)
    rel_diff = abs_diff / (coords_norm[..., np.newaxis] + 1e-8)
    max_rel_diff = np.max(rel_diff)
    mean_rel_diff = np.mean(rel_diff)
    
    logging.info("\n" + "="*60)
    logging.info("比较结果:")
    logging.info("="*60)
    logging.info(f"最大绝对差异: {max_diff:.6e}")
    logging.info(f"平均绝对差异: {mean_diff:.6e}")
    logging.info(f"标准差: {std_diff:.6e}")
    logging.info(f"最大相对差异: {max_rel_diff:.6e}")
    logging.info(f"平均相对差异: {mean_rel_diff:.6e}")
    
    # 检查是否几乎相同
    tolerance = 1e-5
    if max_diff < tolerance:
        logging.info(f"\n✓ 两种方法得到的坐标几乎相同 (max_diff < {tolerance})")
    else:
        logging.warning(f"\n✗ 两种方法得到的坐标有显著差异 (max_diff >= {tolerance})")
        
        # 找出差异最大的位置
        max_diff_idx = np.unravel_index(np.argmax(abs_diff), abs_diff.shape)
        logging.info(f"最大差异位置: frame={max_diff_idx[0]}, residue={max_diff_idx[1]}, axis={max_diff_idx[2]}")
        logging.info(f"  直接方法值: {coords_preprocessed_direct[max_diff_idx]:.6f}")
        logging.info(f"  重建方法值: {coords_reconstructed_permuted[max_diff_idx]:.6f}")
        logging.info(f"  差异: {diff[max_diff_idx]:.6e}")
    
    # 统计信息
    logging.info("\n" + "="*60)
    logging.info("统计信息:")
    logging.info("="*60)
    logging.info(f"直接方法坐标范围:")
    logging.info(f"  X: [{coords_preprocessed_direct[:, :, 0].min():.3f}, {coords_preprocessed_direct[:, :, 0].max():.3f}]")
    logging.info(f"  Y: [{coords_preprocessed_direct[:, :, 1].min():.3f}, {coords_preprocessed_direct[:, :, 1].max():.3f}]")
    logging.info(f"  Z: [{coords_preprocessed_direct[:, :, 2].min():.3f}, {coords_preprocessed_direct[:, :, 2].max():.3f}]")
    logging.info(f"重建方法坐标范围:")
    logging.info(f"  X: [{coords_reconstructed_permuted[:, :, 0].min():.3f}, {coords_reconstructed_permuted[:, :, 0].max():.3f}]")
    logging.info(f"  Y: [{coords_reconstructed_permuted[:, :, 1].min():.3f}, {coords_reconstructed_permuted[:, :, 1].max():.3f}]")
    logging.info(f"  Z: [{coords_reconstructed_permuted[:, :, 2].min():.3f}, {coords_reconstructed_permuted[:, :, 2].max():.3f}]")
    
    return {
        'max_diff': max_diff,
        'mean_diff': mean_diff,
        'std_diff': std_diff,
        'max_rel_diff': max_rel_diff,
        'mean_rel_diff': mean_rel_diff,
        'coords_direct': coords_preprocessed_direct,
        'coords_reconstructed': coords_reconstructed_permuted,
        'x_proc': x_proc,  # (N, 3, window_size) 格式，用于保存PDB
        'protein_id': protein_id,
        'protein_data': protein_data,
    }


def main():
    parser = argparse.ArgumentParser(description="比较coords_preprocessed的两种获取方式")
    parser.add_argument("--data_path", type=str, required=True, help="数据文件路径")
    parser.add_argument("--protein_idx", type=int, default=0, help="蛋白质索引")
    parser.add_argument("--window_idx", type=int, default=0, help="窗口索引")
    parser.add_argument("--device", type=str, default="cuda", help="设备")
    parser.add_argument("--fft_norm", type=str, default="ortho", choices=["ortho", "backward"], help="FFT归一化方式")
    parser.add_argument("--scaling_factor_path", type=str, default=None, help="Scaling factors路径（用于反归一化）")
    parser.add_argument("--save_pdb", action="store_true", help="保存重建的坐标到PDB文件")
    parser.add_argument("--pdb_output_dir", type=str, default=None, help="PDB文件输出目录（默认：数据文件所在目录）")
    parser.add_argument("--save_gt", action="store_true", help="同时保存ground truth坐标到PDB文件")
    
    args = parser.parse_args()
    
    results = compare_coords_preprocessed(
        data_path=args.data_path,
        protein_idx=args.protein_idx,
        window_idx=args.window_idx,
        device=args.device,
        fft_norm=args.fft_norm,
        scaling_factor_path=args.scaling_factor_path,
    )
    
    # 保存PDB文件（如果需要）
    if args.save_pdb:
        # 确定输出目录
        if args.pdb_output_dir:
            output_dir = os.path.abspath(os.path.expanduser(args.pdb_output_dir))
        else:
            output_dir = os.path.dirname(os.path.abspath(args.data_path))
        os.makedirs(output_dir, exist_ok=True)
        
        # 获取aatype
        protein_data = results['protein_data']
        aatype = protein_data.get("amino_acid_types")
        if aatype is None:
            logging.warning("未找到 amino_acid_types，无法保存PDB文件")
        else:
            protein_id = results['protein_id']
            window_idx = args.window_idx
            
            # 获取重建坐标 (N, 3, window_size)
            x_proc = results['x_proc']
            
            # 保存重建的坐标
            reconstructed_output_path = os.path.join(
                output_dir, f"{protein_id}_window{window_idx}_reconstructed.pdb"
            )
            coordinates_to_pdb(
                coordinates=x_proc.cpu(),
                aatype=aatype.cpu() if isinstance(aatype, torch.Tensor) else torch.tensor(aatype),
                output_path=reconstructed_output_path,
                protein_name=f"{protein_id}_window{window_idx}_reconstructed",
                chain_id="A",
                ca_only=True,
            )
            logging.info(f"重建轨迹已保存: {reconstructed_output_path}")
            
            # 保存ground truth坐标（如果需要）
            if args.save_gt:
                coords_direct = results['coords_direct']  # (window_size, N, 3)
                # 转换为 (N, 3, window_size) 格式
                coords_direct_tensor = torch.tensor(coords_direct, dtype=torch.float32)
                coords_direct_permuted = coords_direct_tensor.permute(1, 2, 0).contiguous()  # (N, 3, window_size)
                
                gt_output_path = os.path.join(
                    output_dir, f"{protein_id}_window{window_idx}_ground_truth.pdb"
                )
                coordinates_to_pdb(
                    coordinates=coords_direct_permuted,
                    aatype=aatype.cpu() if isinstance(aatype, torch.Tensor) else torch.tensor(aatype),
                    output_path=gt_output_path,
                    protein_name=f"{protein_id}_window{window_idx}_ground_truth",
                    chain_id="A",
                    ca_only=True,
                )
                logging.info(f"Ground truth轨迹已保存: {gt_output_path}")


if __name__ == "__main__":
    main()
